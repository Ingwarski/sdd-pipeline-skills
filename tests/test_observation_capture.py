"""Typed observations keep payload data out of source dependency discovery."""
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from test_sdd_check import sdd
from observation_capture import encode_observation, snapshot_dependencies


class ObservationCaptureTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="sdd-observation-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        (self.root / "observations").mkdir()
        (self.root / "tests").mkdir()
        (self.root / "output").mkdir()
        self.source = self.root / "tests/probe.txt"
        self.source.write_text("synthetic probe source")
        self.ref = {"path": "tests/probe.txt", "content_hash": hashlib.sha256(self.source.read_bytes()).hexdigest()}

    def discover(self, document, **extra):
        (self.root / "observations/result.json").write_text(json.dumps(document))
        return sdd.history_api().referenced_paths(self.root,
            {"result": {"path": "observations/result.json"}, **extra})

    def test_compact_writer_preserves_observations_without_stdout_copy(self):
        observation = {"assertions": [{"id": "check-a", "result": "failed", "actual": "α"}],
                       "details": "recorded once " * 100}
        stdout = json.dumps(observation).encode()
        data = encode_observation(observation, dependencies=[self.ref], stdout=stdout)
        record = json.loads(data)
        self.assertEqual(observation, record["observations"])
        self.assertEqual(hashlib.sha256(stdout).hexdigest(), record["transport"]["stdout_sha256"])
        self.assertEqual(len(stdout), record["transport"]["stdout_bytes"])
        self.assertNotIn("result", record)  # Serialization never claims acceptance.
        self.assertEqual([self.ref], snapshot_dependencies(record))
        self.assertEqual(1, data.count(observation["details"].encode()))

    def test_incidental_existing_paths_do_not_expand_snapshot(self):
        (self.root / "output/unrelated.txt").write_text("unrelated generated bytes")
        document = json.loads(encode_observation({"path": "output", "source_hashes": {
            "output/unrelated.txt": "observed text, not a source declaration"}}, dependencies=[self.ref]))
        self.assertEqual({"observations/result.json", "tests/probe.txt"}, self.discover(document))

    def test_canonical_source_declaration_is_still_retained(self):
        (self.root / "output/required-fixture.txt").write_text("authored fixture")
        document = json.loads(encode_observation({"path": "output"}, dependencies=[self.ref]))
        found = self.discover(document, required_source_paths=["output/required-fixture.txt"])
        self.assertIn("output/required-fixture.txt", found)

    def test_changed_missing_or_unsafe_declared_dependency_is_rejected(self):
        document = json.loads(encode_observation({}, dependencies=[self.ref]))
        self.source.write_text("changed after observation")
        with self.assertRaisesRegex(ValueError, "observation dependency"):
            self.discover(document)
        self.source.unlink()
        with self.assertRaises((ValueError, FileNotFoundError)):
            self.discover(document)
        with self.assertRaises(ValueError):
            encode_observation({}, dependencies=[{**self.ref, "path": "../outside"}])

    def test_ordinary_json_dependency_discovery_is_unchanged(self):
        (self.root / "output/receipt.txt").write_text("required receipt")
        self.assertIn("output/receipt.txt", self.discover({"receipt_path": "output/receipt.txt"}))

    def test_typed_receipt_cannot_smuggle_undeclared_top_level_fields(self):
        record = json.loads(encode_observation({}, dependencies=[self.ref]))
        record["authority"] = {"path": "tests/probe.txt"}
        with self.assertRaisesRegex(ValueError, "unknown fields"):
            self.discover(record)
        with self.assertRaises(ValueError):
            encode_observation({"invalid": float("nan")})


if __name__ == "__main__":
    unittest.main()
